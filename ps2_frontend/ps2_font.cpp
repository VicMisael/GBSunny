#include "ps2_font.h"

#include <array>
#include <cctype>
#include <cstdint>

namespace ps2_frontend::font {
namespace {

constexpr int FontScale = 2;
constexpr int GlyphWidth = 6 * FontScale;
constexpr unsigned char FirstCharacter = 0x20;
constexpr unsigned char LastCharacter = 0x7F;
constexpr std::size_t GlyphCount = LastCharacter - FirstCharacter + 1;

using Glyph = std::array<std::uint8_t, 5>;
using GlyphTable = std::array<Glyph, GlyphCount>;

constexpr GlyphTable make_glyph_table()
{
    constexpr Glyph fallback{0x02, 0x01, 0x51, 0x09, 0x06};
    GlyphTable glyphs{};
    glyphs.fill (fallback);

    const auto set = [&glyphs](char character, Glyph glyph) {
        glyphs[static_cast<unsigned char>(character) - FirstCharacter] = glyph;
    };

    set(' ', {0, 0, 0, 0, 0});
    set('A', {0x7E, 0x11, 0x11, 0x11, 0x7E});
    set('B', {0x7F, 0x49, 0x49, 0x49, 0x36});
    set('C', {0x3E, 0x41, 0x41, 0x41, 0x22});
    set('D', {0x7F, 0x41, 0x41, 0x22, 0x1C});
    set('E', {0x7F, 0x49, 0x49, 0x49, 0x41});
    set('F', {0x7F, 0x09, 0x09, 0x09, 0x01});
    set('G', {0x3E, 0x41, 0x49, 0x49, 0x7A});
    set('H', {0x7F, 0x08, 0x08, 0x08, 0x7F});
    set('I', {0x00, 0x41, 0x7F, 0x41, 0x00});
    set('J', {0x20, 0x40, 0x41, 0x3F, 0x01});
    set('K', {0x7F, 0x08, 0x14, 0x22, 0x41});
    set('L', {0x7F, 0x40, 0x40, 0x40, 0x40});
    set('M', {0x7F, 0x02, 0x0C, 0x02, 0x7F});
    set('N', {0x7F, 0x04, 0x08, 0x10, 0x7F});
    set('O', {0x3E, 0x41, 0x41, 0x41, 0x3E});
    set('P', {0x7F, 0x09, 0x09, 0x09, 0x06});
    set('Q', {0x3E, 0x41, 0x51, 0x21, 0x5E});
    set('R', {0x7F, 0x09, 0x19, 0x29, 0x46});
    set('S', {0x46, 0x49, 0x49, 0x49, 0x31});
    set('T', {0x01, 0x01, 0x7F, 0x01, 0x01});
    set('U', {0x3F, 0x40, 0x40, 0x40, 0x3F});
    set('V', {0x1F, 0x20, 0x40, 0x20, 0x1F});
    set('W', {0x3F, 0x40, 0x38, 0x40, 0x3F});
    set('X', {0x63, 0x14, 0x08, 0x14, 0x63});
    set('Y', {0x07, 0x08, 0x70, 0x08, 0x07});
    set('Z', {0x61, 0x51, 0x49, 0x45, 0x43});
    set('0', {0x3E, 0x51, 0x49, 0x45, 0x3E});
    set('1', {0x00, 0x42, 0x7F, 0x40, 0x00});
    set('2', {0x62, 0x51, 0x49, 0x49, 0x46});
    set('3', {0x22, 0x41, 0x49, 0x49, 0x36});
    set('4', {0x18, 0x14, 0x12, 0x7F, 0x10});
    set('5', {0x2F, 0x49, 0x49, 0x49, 0x31});
    set('6', {0x3E, 0x49, 0x49, 0x49, 0x32});
    set('7', {0x01, 0x71, 0x09, 0x05, 0x03});
    set('8', {0x36, 0x49, 0x49, 0x49, 0x36});
    set('9', {0x26, 0x49, 0x49, 0x49, 0x3E});
    set('.', {0x00, 0x60, 0x60, 0x00, 0x00});
    set(':', {0x00, 0x36, 0x36, 0x00, 0x00});
    set('/', {0x20, 0x10, 0x08, 0x04, 0x02});
    set('\\', {0x02, 0x04, 0x08, 0x10, 0x20});
    set('-', {0x08, 0x08, 0x08, 0x08, 0x08});
    set('_', {0x40, 0x40, 0x40, 0x40, 0x40});
    set('[', {0x00, 0x7F, 0x41, 0x41, 0x00});
    set(']', {0x00, 0x41, 0x41, 0x7F, 0x00});
    set('(', {0x00, 0x1C, 0x22, 0x41, 0x00});
    set(')', {0x00, 0x41, 0x22, 0x1C, 0x00});
    set('+', {0x08, 0x08, 0x3E, 0x08, 0x08});
    set('?', fallback);
    return glyphs;
}

constexpr GlyphTable Glyphs = make_glyph_table();

const Glyph& glyph_for(char character)
{
    const auto value = static_cast<unsigned char>(character);
    const auto upper = static_cast<unsigned char>(std::toupper(value));
    if (upper < FirstCharacter || upper > LastCharacter) {
        return Glyphs['?' - FirstCharacter];
    }
    return Glyphs[upper - FirstCharacter];
}

} // namespace

void draw_text(SDL_Renderer* renderer, int x, int y, std::string_view text, SDL_Color color)
{
    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    for (const char character : text) {
        const Glyph& glyph = glyph_for(character);
        for (int column = 0; column < static_cast<int>(glyph.size()); ++column) {
            for (int row = 0; row < 7; ++row) {
                if ((glyph[column] & (1U << row)) == 0) {
                    continue;
                }
                const SDL_Rect pixel{
                    x + column * FontScale,
                    y + row * FontScale,
                    FontScale,
                    FontScale};
                SDL_RenderFillRect(renderer, &pixel);
            }
        }
        x += GlyphWidth;
    }
}

} // namespace ps2_frontend::font
